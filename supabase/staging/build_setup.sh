#!/bin/sh
# Builds supabase/staging/setup.sql: every schema file in supabase/, in the
# order they were run on the live project, for a brand-new EMPTY project.
# Paste the result into the staging project's SQL editor and run it once.
#
# NEVER run setup.sql on the live project: secure_schema.sql drops tables.
#
# Left out on purpose:
#   migrate_banks_to_catalog.sql            moves an older bank layout; a new project never had it
#   backfill_sessions_from_transactions.sql data only
#   export_for_parsers.sql                  a read-only query, not schema
#
# When you add a new SQL file to supabase/, add it to the list below too.
set -eu
cd "$(dirname "$0")/.."

FILES="
secure_schema.sql
sync_i_users_from_auth.sql
add_category.sql
add_recipt_link.sql
add_i_raw_data.sql
add_ledger.sql
add_goals.sql
add_income.sql
add_custom_cadence.sql
add_admin_sessions.sql
add_budgets.sql
add_daily_review.sql
add_feedback.sql
launch_account_deletion_and_banks.sql
admin_overview_real_sessions.sql
admin_health_metrics.sql
dedupe_transactions_by_sms.sql
money_senders.sql
add_account_number.sql
drop_ignored_raw_sms.sql
lock_transactions_backup.sql
"
SKIPPED="migrate_banks_to_catalog.sql backfill_sessions_from_transactions.sql export_for_parsers.sql"

# Every .sql file must be either in the list or skipped on purpose.
for f in *.sql; do
  case " $(echo $FILES) $SKIPPED " in
    *" $f "*) ;;
    *) echo "supabase/$f is not in build_setup.sh; add it to FILES or SKIPPED" >&2; exit 1 ;;
  esac
done

OUT=staging/setup.sql
{
  echo "-- STAGING ONLY. Generated by supabase/staging/build_setup.sh. Do not edit."
  echo "-- Never run on the live project: the first file drops tables."
  for f in $FILES; do
    echo
    echo "-- ===================== $f"
    cat "$f"
    echo
  done
} > "$OUT"
echo "Wrote supabase/$OUT"
